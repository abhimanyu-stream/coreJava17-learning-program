/**
 * Best interview shortlist (focus these)
 *
 * If you have limited time, master these 8 first:
 *
 * Must Know	Priority
 * Singleton	⭐
 * Factory	⭐
 * Builder	⭐
 * Strategy	⭐
 * Observer	⭐
 * Proxy	⭐
 * Decorator	⭐
 * Adapter	⭐
 * Spring Boot interview favorites
 *
 * These come up most:
 *
 * Pattern	Spring example
 * Singleton	Beans
 * Factory	BeanFactory
 * Proxy	AOP, Transactions
 * Observer	Events
 * Strategy	Multiple service implementations
 * Template Method	JdbcTemplate
 * Chain of Responsibility	Filter chain
 * Builder	Lombok / builders
 * One-line memory trick
 * Singleton = one object
 * Factory = create object
 * Builder = build step by step
 * Strategy = choose behavior
 * Observer = notify listeners
 * Proxy = control access
 * Decorator = add behavior
 * Adapter = make incompatible work
 * Template = fixed flow + override steps
 * Chain = pass request along handlers
 *
 * These are enough for 90% of interviews.
 */